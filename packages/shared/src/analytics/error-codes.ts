export type ErrorCode = keyof typeof ERROR_CODES;

export function isErrorCode(v: unknown): v is ErrorCode {
  return typeof v === 'string' && Object.prototype.hasOwnProperty.call(ERROR_CODES, v);
}

export function errorMessage(code: ErrorCode): string {
  return ERROR_CODES[code];
}

/**
 * The code for a fixed message a shared validator returned (for example a date rule), or `fallback` when the
 * message is not in the list. Lets screens keep the exact wording while still reporting a code.
 */
export function codeForMessage(message: string | null | undefined, fallback: ErrorCode): ErrorCode {
  if (!message) return fallback;
  for (const [code, text] of Object.entries(ERROR_CODES)) if (text === message) return code as ErrorCode;
  return fallback;
}

