// Turns the AI-generated sticker PNGs (transparent background, white die-cut border already drawn)
// into the app and web assets: trimmed and centred with 4% transparent padding, at 512 px, 256 px,
// plus a 256 px "locked" silhouette (solid #121212 at 12% opacity).
// See docs/design/sticker-prompt-pack.md.
//
// The source PNGs (46 MB) are not committed. They live in the main checkout's `art/stickers/`.
//
// Usage: pnpm --filter @caltracker/scripts exec tsx process-stickers.ts [inDir] [mobileOutDir] [webOutDir]
// Defaults write to apps/mobile/assets/stickers and apps/web/public/stickers in this repo, and also
// regenerate apps/mobile/src/lib/sticker-assets.ts.
import { execFileSync } from 'node:child_process';
import { mkdir, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import sharp from 'sharp';

export const LARGE_SIZE = 512;
export const SMALL_SIZE = 256;
export const LOCKED_SIZE = 256;
/** Transparent margin on every side, as a share of the canvas. */
export const PADDING = 0.04;
export const LOCKED_COLOUR = '#121212'; // ink token
export const LOCKED_ALPHA = 0.12;
const WEBP_QUALITY = 80;

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
/** The source art is not committed; it lives in the main checkout's art/stickers, found from any worktree. */
function defaultInDir(): string {
  const common = execFileSync('git', ['rev-parse', '--path-format=absolute', '--git-common-dir'], { cwd: repoRoot, encoding: 'utf8' }).trim();
  return path.join(path.dirname(common), 'art/stickers');
}
export const DEFAULT_MOBILE_DIR = path.join(repoRoot, 'apps/mobile/assets/stickers');
export const DEFAULT_WEB_DIR = path.join(repoRoot, 'apps/web/public/stickers');
export const ASSET_MAP_FILE = path.join(repoRoot, 'apps/mobile/src/lib/sticker-assets.ts');

/** Square 512 px canvas with the trimmed artwork centred inside the padding. */
async function placeOnCanvas(file: string, size: number): Promise<Buffer> {
  const inner = Math.round(size * (1 - 2 * PADDING));
  const trimmed = await sharp(file).ensureAlpha().trim({ threshold: 10 }).png().toBuffer();
  const fitted = await sharp(trimmed).resize(inner, inner, { fit: 'inside' }).png().toBuffer();
  const { width = inner, height = inner } = await sharp(fitted).metadata();
  return sharp({ create: { width: size, height: size, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } })
    .composite([{ input: fitted, left: Math.round((size - width) / 2), top: Math.round((size - height) / 2) }])
    .png()
    .toBuffer();
}

/** Writes `<key>.webp`, `<key>-sm.webp` and `<key>-locked.webp` into every folder. Returns the file names. */
export async function processSticker(file: string, outDirs: string[]): Promise<string[]> {
  const key = path.basename(file, '.png');
  const meta = await sharp(file).metadata();
  if (!meta.hasAlpha) throw new Error(`${key}: needs a transparent background (no alpha channel)`);

  const large = await placeOnCanvas(file, LARGE_SIZE);
  const small = await sharp(large).resize(SMALL_SIZE, SMALL_SIZE).webp({ quality: WEBP_QUALITY, alphaQuality: 90 }).toBuffer();
  const largeWebp = await sharp(large).webp({ quality: WEBP_QUALITY, alphaQuality: 90 }).toBuffer();

  // Two steps: sharp runs `extractChannel` after `linear` in one pipeline, which would scale the wrong channel.
  const fullAlpha = await sharp(large).resize(LOCKED_SIZE, LOCKED_SIZE).extractChannel('alpha').png().toBuffer();
  const alpha = await sharp(fullAlpha).linear(LOCKED_ALPHA, 0.5).toColourspace('b-w').png().toBuffer();
  const lockedWebp = await sharp({ create: { width: LOCKED_SIZE, height: LOCKED_SIZE, channels: 3, background: LOCKED_COLOUR } })
    .joinChannel(alpha)
    .webp({ lossless: true, exact: true })
    .toBuffer();

  const outputs: [string, Buffer][] = [
    [`${key}.webp`, largeWebp],
    [`${key}-sm.webp`, small],
    [`${key}-locked.webp`, lockedWebp],
  ];
  for (const dir of outDirs) {
    await mkdir(dir, { recursive: true });
    for (const [name, buf] of outputs) await writeFile(path.join(dir, name), buf);
  }
  return outputs.map(([name]) => name);
}

/** The static `require` map. Metro needs literal paths, so this is generated, not computed. */
export function assetMapSource(keys: string[]): string {
  const entries = keys
    .map(
      (k) =>
        `  '${k}': {\n    lg: require('../../assets/stickers/${k}.webp'),\n    sm: require('../../assets/stickers/${k}-sm.webp'),\n    locked: require('../../assets/stickers/${k}-locked.webp'),\n  },`,
    )
    .join('\n');
  return `// Generated by scripts/process-stickers.ts. Do not edit by hand: rerun the script instead.
/* eslint-disable @typescript-eslint/no-require-imports, @typescript-eslint/no-unsafe-assignment -- Metro needs literal require paths */
import type { ImageSourcePropType } from 'react-native';

export type StickerImageSize = 'lg' | 'sm' | 'locked';

const IMAGES: Record<string, Record<StickerImageSize, ImageSourcePropType>> = {
${entries}
};

/** The bundled art for a sticker: \`lg\` 512 px, \`sm\` 256 px, \`locked\` 256 px silhouette. */
export function stickerImage(key: string, size: StickerImageSize): ImageSourcePropType {
  const set = IMAGES[key];
  if (!set) throw new Error(\`No sticker art for "\${key}"\`);
  return set[size];
}
`;
}

export async function processStickers(inDir: string, outDirs: string[]): Promise<string[]> {
  const files = (await readdir(inDir)).filter((f) => f.toLowerCase().endsWith('.png')).sort();
  for (const f of files) {
    await processSticker(path.join(inDir, f), outDirs);
    console.log(`processed ${f}`);
  }
  return files.map((f) => path.basename(f, '.png'));
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const [inDir = defaultInDir(), mobileDir = DEFAULT_MOBILE_DIR, webDir = DEFAULT_WEB_DIR] = process.argv.slice(2);
  const keys = await processStickers(inDir, [mobileDir, webDir]);
  await writeFile(ASSET_MAP_FILE, assetMapSource(keys));
  console.log(`wrote ${ASSET_MAP_FILE}`);
}
