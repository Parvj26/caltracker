// Rebuilds exercise-images-manifest.json and exercise-image-match-report.md from a local copy of free-exercise-db at
// the pinned commit. Run by a person after changing the pinned commit, the extras or the alias table; never in CI.
// It only reads JSON and picture files from the copy and runs nothing from it.
//
// Usage: pnpm --filter @caltracker/scripts exec tsx build-exercise-image-manifest.ts <path-to-free-exercise-db-copy>
// Get the copy with: curl -L https://codeload.github.com/yuhonas/free-exercise-db/tar.gz/<PINNED_SHA> | tar -xz
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { exerciseImageObjectPath, type FreeExercise } from '@caltracker/shared';
import { loadExtras } from './caltracker-extras';
import { matchExercises, type AliasTable, type MatchResult } from './exercise-image-match';
import { MANIFEST_FILE, sha256Hex, validateManifest, type ImageManifest } from './exercise-images';
import { PINNED_SHA } from './import-exercises';

const here = path.dirname(fileURLToPath(import.meta.url));
export const ALIASES_FILE = path.join(here, 'exercise-image-aliases.json');
export const REPORT_FILE = path.join(here, 'exercise-image-match-report.md');

const REPO = 'https://github.com/yuhonas/free-exercise-db';
const LICENCE = 'Unlicense';
const UNLICENSE_FIRST_LINE = 'This is free and unencumbered software released into the public domain.';

export function renderReport(
  result: MatchResult,
  library: { id: string; name: string }[],
  sourceNames: Map<string, string>,
  table: AliasTable,
): string {
  const names = new Map(library.map((l) => [l.id, l.name]));
  const by = (kind: string) => Object.entries(result.matches).filter(([, m]) => m.kind === kind);
  const own = by('own');
  const exact = by('exact');
  const alias = by('alias');
  const lines = [
    '# Exercise picture matches',
    '',
    `Generated by \`build-exercise-image-manifest.ts\` from free-exercise-db @ \`${PINNED_SHA}\` (${LICENCE}).`,
    'Do not edit by hand: change `exercise-image-aliases.json` and re-run the script.',
    '',
    '| | Count |',
    '| --- | ---: |',
    `| Library exercises | ${library.length} |`,
    `| Own pictures (free-exercise-db exercise with its own photos) | ${own.length} |`,
    `| Exact name match (after normalising) | ${exact.length} |`,
    `| Alias match (hand-checked) | ${alias.length} |`,
    `| **With a picture** | **${own.length + exact.length + alias.length}** |`,
    `| **Unmatched (no picture)** | **${result.unmatched.length}** |`,
    '',
    '## Exact name matches',
    '',
    ...(exact.length === 0 ? ['None.'] : exact.map(([id, m]) => `- ${names.get(id)} (\`${id}\`) -> ${sourceNames.get(m.sourceId)} (\`${m.sourceId}\`)`)),
    '',
    '## Alias matches',
    '',
    ...(alias.length === 0
      ? ['None.']
      : alias.map(([id, m]) => `- ${names.get(id)} (\`${id}\`) -> ${sourceNames.get(m.sourceId)} (\`${m.sourceId}\`): ${table.aliasNotes[id]}`)),
    '',
    '## Unmatched',
    '',
    ...(result.unmatched.length === 0
      ? ['None.']
      : result.unmatched.map((u) => {
          const turnedDown = table.rejected.filter((r) => r.library === u.id).map((r) => `${r.source} (${r.reason.replace(/\.$/, '')})`);
          const extra = u.reason === 'ambiguous' ? ` Several equal candidates: ${u.candidates.join(', ')}.` : '';
          return `- ${u.name} (\`${u.id}\`).${extra}${turnedDown.length ? ` Looked at and turned down: ${turnedDown.join('; ')}.` : ''}`;
        })),
    '',
    '## Licence',
    '',
    `All pictures come from ${REPO} at commit \`${PINNED_SHA}\`, whose LICENSE.md is the Unlicense (public domain): ${REPO}/blob/${PINNED_SHA}/LICENSE.md`,
    '',
    '## Sources not used',
    '',
    '- wger.de (CC-BY-SA): checked for the unmatched exercises and not used. Its closest candidates were user uploads whose',
    '  licence could not be trusted (commercial-looking illustrations, one with a watermark, marked CC-BY-SA), and the one',
    '  trustworthy set (Everkinetic line drawings) covered only an exercise already matched here. Using it would also need',
    '  per-picture attribution shown in both apps.',
    '- No search-engine or gym-brand pictures are used.',
    '',
  ];
  return lines.join('\n');
}

async function main(): Promise<void> {
  const dir = process.argv[2];
  if (!dir) throw new Error('Usage: build-exercise-image-manifest.ts <path-to-free-exercise-db-copy>');
  const root = path.resolve(process.env.INIT_CWD ?? process.cwd(), dir);

  const licenceText = await readFile(path.join(root, 'LICENSE.md'), 'utf8');
  if (!licenceText.startsWith(UNLICENSE_FIRST_LINE)) throw new Error('LICENSE.md is not the Unlicense; stopping.');

  const list = JSON.parse(await readFile(path.join(root, 'dist', 'exercises.json'), 'utf8')) as FreeExercise[];
  const extras = await loadExtras(list.map((e) => e.id));
  const library = [...list, ...extras].map((e) => ({ id: e.id, name: e.name }));
  const table = JSON.parse(await readFile(ALIASES_FILE, 'utf8')) as AliasTable;
  const result = matchExercises(library, list, table);

  const exercisesDir = path.join(root, 'exercises');
  const manifest: ImageManifest = {
    source: { name: 'free-exercise-db', repo: REPO, commit: PINNED_SHA, licence: LICENCE, licenceFile: `${REPO}/blob/${PINNED_SHA}/LICENSE.md` },
    exercises: {},
  };
  for (const [id, m] of Object.entries(result.matches).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
    const images = [];
    for (const p of m.images) {
      exerciseImageObjectPath(p); // throws on any path that could leave the exercises folder
      images.push({ path: p, sha256: sha256Hex(await readFile(path.join(exercisesDir, p))), licence: LICENCE });
    }
    manifest.exercises[id] = { match: m.kind, sourceId: m.sourceId, images };
  }
  validateManifest(manifest);
  await writeFile(MANIFEST_FILE, `${JSON.stringify(manifest, null, 1)}\n`);
  await writeFile(REPORT_FILE, renderReport(result, library, new Map(list.map((e) => [e.id, e.name])), table));
  console.log(`Wrote ${Object.keys(manifest.exercises).length} exercises to the manifest; ${result.unmatched.length} unmatched.`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main().catch((e: unknown) => {
    console.error(e instanceof Error ? e.message : e);
    process.exit(1);
  });
}
